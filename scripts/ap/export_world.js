// Generates worlds/alundra/data.py (Archipelago world data) from the randomizer's data files and default preset.
// Usage: node scripts/ap/export_world.js [path/to/Archipelago/worlds/alundra]
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '../..');
const dataDir = path.join(root, 'src/main/resources/data');
const outDir = process.argv[2] || path.join(root, '../archipelago-alundra/worlds/alundra');
const readJson = f => JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\s*\/\/.*$/gm, ''));

const items = readJson(path.join(dataDir, 'item.json'));
const sources = readJson(path.join(dataDir, 'item_source.json'));
const paths = readJson(path.join(dataDir, 'world_path.json'));
const nodes = readJson(path.join(dataDir, 'world_node.json'));
const preset = readJson(path.join(root, 'presets/default.json'));
const rs = preset.randomizerSettings;

const ITEM_BASE = 0xA1000000 >>> 0, LOCATION_BASE = ITEM_BASE + 0x1000;
const CRESTS = ['Ruby Crest', 'Sapphire Crest', 'Topaz Crest', 'Agate Crest', 'Emerald Crest', 'Garnet Crest', 'Diamond Crest'];
const FILLER = new Set(['Herbs', 'Strength Tonic', 'Wonder Essence', '1 Gilder', '5 Gilder', '10 Gilder', '30 Gilder']);

const requiredItems = new Set();
for (const p of paths) for (const i of p.requiredItems || []) requiredItems.add(typeof i === 'string' ? i : i.name);
for (const c of CRESTS) requiredItems.add(c);

// Preset item source names have the vanilla item appended, e.g. 'Merrick's Shop: ... (Spirit Wand)'
const sourceName = presetName => {
    const found = sources.find(s => s.name === presetName || `${s.name} (${s.vanillaItem})` === presetName);
    if (!found) throw new Error('Unknown item source in preset: ' + presetName);
    return found.name;
};

const py = v => JSON.stringify(v).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None');
const lines = ['# Generated by scripts/ap/export_world.js in the randomizer repository. Do not edit by hand.', ''];

const realItems = items.map((it, index) => ({ it, index })).filter(({ it }) => it.name !== 'Nothing' && !it.name.startsWith('Item 0x'));
lines.push('# name -> (id, classification) where classification is "progression", "useful" or "filler"');
lines.push('ITEMS = {');
for (const { it, index } of realItems) {
    const cls = requiredItems.has(it.name) ? 'progression' : FILLER.has(it.name) ? 'filler' : 'useful';
    lines.push(`    ${py(it.name)}: (${ITEM_BASE + index}, ${py(cls)}),`);
}
lines.push('}', '');

lines.push('# name -> (id, region)');
lines.push('LOCATIONS = {');
sources.forEach((s, index) => lines.push(`    ${py(s.name)}: (${LOCATION_BASE + index}, ${py(s.nodeId)}),`));
lines.push('}', '');

lines.push('REGIONS = ' + py(Object.keys(nodes)), '');

lines.push('# (from, to, two_way, {item: count}, [required regions])');
lines.push('PATHS = [');
for (const p of paths) {
    const need = {};
    for (const i of p.requiredItems || []) {
        const name = typeof i === 'string' ? i : i.name;
        need[name] = (need[name] || 0) + (typeof i === 'string' ? 1 : i.quantity);
    }
    lines.push(`    (${py(p.fromId)}, ${py(p.toId)}, ${py(!!p.twoWay)}, ${py(need)}, ${py(p.requiredNodes || [])}),`);
}
lines.push(']', '');

lines.push('START_REGION = "inoa"', 'GOAL_REGION = "end"', '');
lines.push('STARTING_INVENTORY = ' + py(rs.startingInventory), '');
lines.push('CRESTS = ' + py(CRESTS), '');
const pool = { ...rs.itemsDistribution };
lines.push('# Default pool of the randomizer, without crests (they are added from the crest_count option)');
lines.push('ITEM_POOL = ' + py(pool), '');
lines.push('FIXED_LOCATIONS = ' + py(Object.fromEntries(Object.entries(rs.fixedItemSources).map(([k, v]) => [sourceName(k), v]))), '');
lines.push('NO_PROGRESSION_LOCATIONS = ' + py(rs.itemSourcesWithoutProgression.map(sourceName)), '');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'data.py'), lines.join('\n') + '\n');
const total = Object.values(pool).reduce((a, b) => a + b, 0);
console.log(`Wrote ${path.join(outDir, 'data.py')}: ${realItems.length} items, ${sources.length} locations, pool ${total}+7 crests`);
